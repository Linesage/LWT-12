"""Конфигурация бинарной HDC-модели. Все размеры — в битах."""

from __future__ import annotations

import math
from dataclasses import dataclass

import torch

DEV = "cuda" if torch.cuda.is_available() else "cpu"

SRC_WEIGHT = 2.0
"""Вес голоса одного источника в majority.

Флип источника меняет сумму голосов ровно на `2*SRC_WEIGHT` — на этом держится
точный критерий достижимости в обратном проходе.
"""


@dataclass(frozen=True)
class HDCConfig:
    """Гиперпараметры модели.

    Веса residual-голосов (`res_ratio_*`) — несущая конструкция, а не косметика.
    Голос источника имеет вес `SRC_WEIGHT = 2`, вес residual —
    `2*round(ratio*k) + 1`. Отсюда жёсткое ограничение:

        ratio < SRC_WEIGHT / 2 = 1.0

    При `ratio >= 1` вес residual превышает суммарную силу источников
    `2*SRC_WEIGHT*k`, majority физически не может переключиться, и слой
    становится тождественным — обратный проход не даёт его весам ни одного
    голоса. Увеличение `k` не спасает: обе величины растут по `k` линейно.

    С другой стороны, слишком малый `ratio` даёт источникам затирать состояние.
    Замер: при `topk_slots=1, ratio=0.5` один слот памяти имеет вес 4 против
    residual 3 и полностью перебивает результат attention — потолок падает до
    0.000. Поэтому `ratio` надо держать близко к границе, а `topk_slots` — больше
    единицы: тогда для правки нужен КОНСЕНСУС нескольких слотов
    (`w_res / (2*SRC_WEIGHT)` штук), а одиночный шумный слот бессилен.
    Рабочая точка: `topk_slots=8, res_ratio_mem=0.75` — нужно 3.2 согласных
    слота из 8, потолок 1.000.

    `topk_attn` — не «сколько внимания», а «сколько шума». Для точного
    извлечения из одной позиции он должен быть 1: при 2 точность падает с 1.00
    до 0.28, при 4 — до 0.12, потому что лишние источники подмешивают случайные
    гипервекторы с тем же весом.

    `parallel_branches` — как соединяются attention и ассоциативная память.
    Последовательно (`False`) память читает ВЫХОД attention, и до неё не доходит
    исходный токен: замер показал совпадение входа памяти с текущим токеном лишь
    в 35% случаев, из-за чего задача `markov` (отображение «токен -> следующий»)
    держалась на 52% потолка даже с вручную заполненной таблицей переходов.
    Параллельно (`True`) обе ветки читают один вход и голосуют в ОДНОМ majority
    вместе с residual — это и ближе к residual-схеме обычного трансформера, и
    даёт один необратимый сайт на слой вместо двух.

    Но параллельность создаёт новую проблему: ветки голосуют ПРОТИВ друг друга.
    Замер на `markov` с вручную заполненной таблицей переходов: память выбирает
    верный слот в 100% случаев, но при равных весах итог 0.13, а если оставить
    только память — 0.364 (выше потолка 1/3). Задаче нужна память, а attention
    подмешивает свой ответ с тем же весом. Отсюда `branch_weight_*`: вес ветки
    задаётся конфигурацией, а не фиксирован. Это единственный способ выразить
    «какой механизм здесь главный» в схеме без обучаемых вещественных весов.

    `mem_gate_margin` решает ту же проблему принципиальнее. Необученная память
    состоит из случайных гипервекторов, и её top-k слоты — чистый шум, который
    в параллельной схеме голосует наравне с attention (замер: induction падает с
    1.000 до 0.000 при `branch_weight_mem >= 0.25`). Порог требует, чтобы
    выбранный слот был ближе к состоянию, чем случайный: близость случайных
    гипервекторов даёт `score ~ N(0, sqrt(H))`, поэтому порог задаётся в
    единицах этого стандартного отклонения. Слоты, не прошедшие порог, не
    голосуют вовсе — память включается только там, где реально что-то помнит.
    Замер: при `gate=4` необученная память перестаёт мешать (induction 1.000
    против 0.000 без порога), а обученная работает по-прежнему.

    `attn_gate_margin` — то же для attention. Задачам вроде `markov` attention не
    нужен вовсе, и без порога он подмешивает свой ответ: 0.13 против 0.364, если
    его отключить. Порог решает это без ручного отключения ветки — attention
    молчит там, где не нашёл достаточно похожей позиции.

    `gate_fallback` нужен, потому что порог отсекает всё на СТАРТЕ обучения:
    у случайных гипервекторов максимальная близость около 4 сигм, а у обученных
    — 32 сигмы. Без fallback ни один источник не голосует, обратный проход не
    видит источников и веса не получают голосов вообще. Fallback пропускает
    единственного лучшего кандидата даже ниже порога: он почти не влияет на
    majority (один голос против residual), но сохраняет путь для обучения.
    """

    d_hidden: int = 32768
    n_layers: int = 4
    n_slots: int = 4096
    topk_slots: int = 8            # >1: правка памяти требует консенсуса слотов
    vocab: int = 4096
    seq_len: int = 512
    logit_std: float = 0.5
    topk_attn: int = 1             # >1 разбавляет сигнал случайными векторами
    parallel_branches: bool = True   # attention и память читают ОДИН вход
    branch_weight_attn: float = 1.0  # множитель голосов attention
    branch_weight_mem: float = 1.0   # множитель голосов памяти
    mem_gate_margin: float = 4.0     # порог близости для срабатывания памяти
    attn_gate_margin: float = 4.0    # порог близости для срабатывания attention
    gate_fallback: bool = True       # при пустом гейте пропускать лучший кандидат
    res_ratio_attn: float = 0.25   # < 1.0, иначе attention не может обновить x
    res_ratio_mem: float = 0.75    # < 1.0, иначе память заморожена

    def __post_init__(self) -> None:
        """Проверка условий, при нарушении которых слой становится мёртвым."""
        limit = SRC_WEIGHT / 2
        for name in ("res_ratio_attn", "res_ratio_mem"):
            value = getattr(self, name)
            if value >= limit:
                raise ValueError(
                    f"{name}={value} >= {limit}: вес residual превысит силу "
                    f"источников, majority не сможет переключиться и слой "
                    f"перестанет обучаться")

    @property
    def tau(self) -> float:
        """Температура логитов, привязанная к ширине состояния.

        Скалярное произведение случайных гипервекторов масштабируется как
        `sqrt(H)`, поэтому фиксированное `tau` при смене `H` либо схлопывает
        логиты, либо уводит их в сотни.
        """
        return math.sqrt(self.d_hidden) / self.logit_std

    @property
    def bit_params(self) -> int:
        per_layer = 2 * self.n_slots * self.d_hidden + 3 * self.d_hidden
        return self.n_layers * per_layer + self.vocab * self.d_hidden
